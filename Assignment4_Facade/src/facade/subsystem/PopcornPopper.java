package facade.subsystem;

public class PopcornPopper {
    public void on() {
        System.out.println("Popcorn Popper is ON");
    }

    public void pop() {
        System.out.println("Popcorn Popper is popping delicious popcorn!");
    }

    public void off() {
        System.out.println("Popcorn Popper is OFF");
    }
}